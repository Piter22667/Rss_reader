-- Topic categories are stable per feed source and are reused between runs.
CREATE TABLE summary_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_source_id BIGINT NOT NULL REFERENCES feed_sources (id) ON DELETE CASCADE,
    category_key VARCHAR(80) NOT NULL,
    label VARCHAR(160) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMPTZ,
    CONSTRAINT uq_summary_categories_source_key UNIQUE (feed_source_id, category_key)
);

-- One generated topic overview belongs to one preference version.
CREATE TABLE summary_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_source_id BIGINT NOT NULL REFERENCES feed_sources (id) ON DELETE CASCADE,
    preference_version_id BIGINT NOT NULL REFERENCES preference_versions (id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES summary_categories (id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    summary_text TEXT NOT NULL,
    article_count INTEGER NOT NULL CHECK (article_count > 0),
    model_name VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_summary_groups_version ON summary_groups (preference_version_id);
CREATE INDEX idx_summary_groups_category ON summary_groups (category_id);

-- An article summary can belong to at most one topic overview per preference version.
ALTER TABLE article_summaries
    ADD COLUMN summary_group_id BIGINT REFERENCES summary_groups (id) ON DELETE SET NULL;

CREATE INDEX idx_article_summaries_group ON article_summaries (summary_group_id);
